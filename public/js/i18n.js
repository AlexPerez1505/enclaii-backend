  var SKIP_TAGS = { SCRIPT: 1, STYLE: 1, NOSCRIPT: 1, TEXTAREA: 1, CODE: 1, PRE: 1 };
  var ATTRS = ['placeholder', 'title', 'aria-label', 'alt'];

  function getLang() {
    try { return localStorage.getItem(STORAGE_KEY) || 'es'; } catch (e) { return 'es'; }
  }
  function setLang(lang) {
    try { localStorage.setItem(STORAGE_KEY, lang); } catch (e) {}
  }

  function translateString(s) {
    var key = s.trim();
    if (!key) return null;
    if (!Object.prototype.hasOwnProperty.call(DICT, key)) return null;
    var translated = DICT[key];
    // Conservar el espacio en blanco original alrededor del texto.
    return s.replace(key, translated);
  }

  function isProtected(el) {
    return !!(el && el.closest && el.closest('[data-no-i18n]'));
  }

  function translateTextNode(node) {
    if (!node.nodeValue) return;
    var parent = node.parentNode;
    if (parent && SKIP_TAGS[parent.nodeName]) return;
    if (isProtected(parent)) return;
    var out = translateString(node.nodeValue);
    if (out !== null && out !== node.nodeValue) {
      if (node.__esOriginal === undefined) node.__esOriginal = node.nodeValue;
      node.nodeValue = out;
    }
  }

  function translateAttrs(el) {
    if (!el.getAttribute) return;
    if (isProtected(el)) return;
    for (var i = 0; i < ATTRS.length; i++) {
      var a = ATTRS[i];
      if (!el.hasAttribute(a)) continue;
      var out = translateString(el.getAttribute(a));
      if (out !== null && out !== el.getAttribute(a)) el.setAttribute(a, out);
    }
  }

  function walk(root) {
    if (!root) return;
    // Atributos del propio elemento
    if (root.nodeType === 1) translateAttrs(root);
    var tw = document.createTreeWalker(root, NodeFilter.SHOW_TEXT, null, false);
    var batch = [];
    var n;
    while ((n = tw.nextNode())) batch.push(n);
    for (var i = 0; i < batch.length; i++) translateTextNode(batch[i]);
    // Atributos de descendientes
    if (root.querySelectorAll) {
      var els = root.querySelectorAll('[placeholder],[title],[aria-label],[alt]');
      for (var j = 0; j < els.length; j++) translateAttrs(els[j]);
    }
  }

  function applyIfNeeded() {
    if (getLang() !== 'en') return;
    document.documentElement.lang = 'en';
    walk(document.body);
    observe();
  }

  var observer = null;
  function observe() {
    if (observer || !window.MutationObserver) return;
    observer = new MutationObserver(function (mutations) {
      for (var i = 0; i < mutations.length; i++) {
        var m = mutations[i];
        if (m.type === 'characterData') {
          translateTextNode(m.target);
        } else if (m.type === 'attributes' && m.target.nodeType === 1) {
          translateAttrs(m.target);
        } else {
          for (var k = 0; k < m.addedNodes.length; k++) {
            var node = m.addedNodes[k];
            if (node.nodeType === 3) translateTextNode(node);
            else if (node.nodeType === 1) walk(node);
          }
        }
      }
    });
    observer.observe(document.body, {
      childList: true, subtree: true, characterData: true,
      attributes: true, attributeFilter: ATTRS
    });
  }

  // API pública: cambiar idioma. Recarga para aplicar limpio (ES original / EN traducido).
  window.enclaiiI18n = {
    get: getLang,
    set: function (lang) {
      lang = (lang === 'en') ? 'en' : 'es';
      if (lang === getLang()) return;
      setLang(lang);
      window.location.reload();
    }
  };

  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', applyIfNeeded);
  } else {
    applyIfNeeded();
  }
